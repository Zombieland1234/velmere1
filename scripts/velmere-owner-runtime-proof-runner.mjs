#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { spawnSync } from 'node:child_process';

const args = new Set(process.argv.slice(2));
const execute = args.has('--execute');
const strict = args.has('--strict');
const outDir = 'reports/pass2151-owner-runtime-proof-runner';
const receiptsDir = 'receipts/runtime';
fs.mkdirSync(outDir, { recursive: true });
fs.mkdirSync(receiptsDir, { recursive: true });

const requiredNode = '24.18.0';
const requiredNpm = '11.16.0';
const gates = [
  { gateId: 'clean_install', command: ['npm', ['ci', '--no-audit', '--no-fund', '--progress=false']], requiredEnv: [], timeoutMs: 600000, source: 'local_or_github_actions' },
  { gateId: 'typecheck', command: ['npm', ['run', 'typecheck']], requiredEnv: [], timeoutMs: 300000, source: 'local_or_github_actions' },
  { gateId: 'build', command: ['npm', ['run', 'build']], requiredEnv: [], timeoutMs: 600000, source: 'vercel_or_github_actions' },
  { gateId: 'supabase', command: ['npm', ['run', 'supabase:remote:checklist']], requiredEnv: ['NEXT_PUBLIC_SUPABASE_URL','NEXT_PUBLIC_SUPABASE_ANON_KEY','SUPABASE_SERVICE_ROLE_KEY'], timeoutMs: 180000, source: 'supabase_cli_or_sql_editor' },
  { gateId: 'stripe', command: ['npm', ['run', 'stripe:webhook:replay:harness']], requiredEnv: ['STRIPE_SECRET_KEY','STRIPE_WEBHOOK_SECRET','NEXT_PUBLIC_STRIPE_PUBLISHABLE_KEY'], timeoutMs: 180000, source: 'stripe_cli' },
  { gateId: 'provider', command: ['npm', ['run', 'provider:sandbox:harness']], requiredEnv: ['PRINTFUL_API_TOKEN','PRINTFUL_STORE_ID'], timeoutMs: 180000, source: 'printful_or_tapstitch_sandbox' },
  { gateId: 'hosted_smoke', command: ['npm', ['run', 'smoke:hosted-pack']], requiredEnv: ['VELMERE_HOSTED_BASE_URL'], timeoutMs: 180000, source: 'hosted_browser_smoke' },
  { gateId: 'admin_auth', command: ['npm', ['run', 'verify:admin-auth-session-idempotency']], requiredEnv: ['VELMERE_ADMIN_SESSION_SECRET','VELMERE_ADMIN_OWNER_EMAILS'], timeoutMs: 120000, source: 'signed_admin_session_smoke' },
  { gateId: 'legal_owner_review', command: ['node', ['scripts/velmere-owner-legal-review-receipt.mjs', '--confirm']], requiredEnv: [], timeoutMs: 60000, source: 'owner_review' },
];

function sha256Text(text) { return crypto.createHash('sha256').update(text || '').digest('hex'); }
function getVersion(bin, args) {
  const r = spawnSync(bin, args, { encoding: 'utf8', timeout: 10000 });
  return (r.stdout || r.stderr || '').trim();
}
function redact(text='') {
  let out = String(text);
  for (const key of Object.keys(process.env)) {
    if (/(SECRET|TOKEN|KEY|PASSWORD|WEBHOOK|SERVICE_ROLE)/i.test(key) && process.env[key]) {
      out = out.split(process.env[key]).join(`[REDACTED_${key}]`);
    }
  }
  out = out.replace(/(sk_live_|sk_test_|pk_live_|pk_test_)[A-Za-z0-9_-]+/g, '$1[REDACTED]');
  out = out.replace(/(whsec_)[A-Za-z0-9_-]+/g, '$1[REDACTED]');
  out = out.replace(/(eyJ[A-Za-z0-9_\-.]{20,})/g, '[REDACTED_JWT_LIKE]');
  return out;
}
function now() { return new Date().toISOString(); }
function commandString([bin, argv]) { return [bin, ...argv].join(' '); }
function makeReceipt(gate, status, exitCode, startedAt, endedAt, logPath, summary) {
  const log = fs.existsSync(logPath) ? fs.readFileSync(logPath, 'utf8') : '';
  return {
    schema: 'velmere.runtime.receipt.v1',
    gateId: gate.gateId,
    source: gate.source,
    status,
    requiredFor90: true,
    command: commandString(gate.command),
    environment: { node: process.version, npm: getVersion('npm', ['-v']), target: execute ? 'owner_runtime_execute' : 'owner_runtime_plan' },
    timing: { startedAt, endedAt },
    result: { exitCode, summary, artifactPath: logPath, redactedLogPath: logPath, sha256: sha256Text(log) },
    reviewer: { owner: 'Marcin Bajak / Velmère', reviewedAt: endedAt, note: 'Auto-generated by PASS2151 owner runtime proof runner; secrets are redacted before receipt attachment.' },
  };
}
function writeJson(file, data) { fs.mkdirSync(path.dirname(file), { recursive: true }); fs.writeFileSync(file, JSON.stringify(data, null, 2)); }

const nodeVersion = process.version.replace(/^v/, '');
const npmVersion = getVersion('npm', ['-v']);
const runtimeMismatch = nodeVersion !== requiredNode || npmVersion !== requiredNpm;
const planned = [];
const executed = [];

for (const gate of gates) {
  const missingEnv = gate.requiredEnv.filter((key) => !process.env[key]);
  const base = {
    gateId: gate.gateId,
    command: commandString(gate.command),
    requiredEnv: gate.requiredEnv,
    missingEnv,
    timeoutMs: gate.timeoutMs,
    mode: execute ? 'execute' : 'plan',
    runtimeMismatch,
  };
  planned.push(base);
  if (!execute) continue;

  const startedAt = now();
  const logPath = path.join(outDir, `${gate.gateId}.log`);
  let status;
  let exitCode;
  let summary;
  if (runtimeMismatch && ['clean_install','typecheck','build'].includes(gate.gateId)) {
    summary = `Runtime mismatch: required Node ${requiredNode}/npm ${requiredNpm}, got Node ${nodeVersion}/npm ${npmVersion}.`;
    fs.writeFileSync(logPath, summary + '\n');
    status = 'FAIL';
    exitCode = 100;
  } else if (missingEnv.length) {
    summary = `Missing required environment keys: ${missingEnv.join(', ')}`;
    fs.writeFileSync(logPath, summary + '\n');
    status = 'FAIL';
    exitCode = 101;
  } else {
    const [bin, argv] = gate.command;
    const result = spawnSync(bin, argv, { encoding: 'utf8', timeout: gate.timeoutMs, shell: process.platform === 'win32' });
    exitCode = result.status ?? (result.signal ? 124 : 1);
    const raw = [
      `$ ${commandString(gate.command)}`,
      `exitCode=${exitCode}`,
      `signal=${result.signal || ''}`,
      '--- stdout ---',
      result.stdout || '',
      '--- stderr ---',
      result.stderr || '',
    ].join('\n');
    fs.writeFileSync(logPath, redact(raw));
    status = exitCode === 0 ? 'PASS' : 'FAIL';
    summary = exitCode === 0 ? `${gate.gateId} command passed.` : `${gate.gateId} command failed with exit code ${exitCode}.`;
  }
  const endedAt = now();
  const receipt = makeReceipt(gate, status, exitCode, startedAt, endedAt, logPath, summary);
  writeJson(path.join(receiptsDir, `${gate.gateId}.receipt.json`), receipt);
  executed.push({ ...base, status, exitCode, logPath, receiptPath: path.join(receiptsDir, `${gate.gateId}.receipt.json`) });
  if (strict && status !== 'PASS') break;
}

const report = {
  pass: 'PASS2151',
  name: 'Owner runtime proof runner',
  status: execute ? (executed.every((g) => g.status === 'PASS') && executed.length === gates.length ? 'ALL_GATES_EXECUTED_PASS' : 'EXECUTED_BUT_LOCKED') : 'PLAN_READY_EXECUTE_IN_OWNER_RUNTIME',
  execute,
  strict,
  requiredRuntime: { node: requiredNode, npm: requiredNpm },
  observedRuntime: { node: nodeVersion, npm: npmVersion },
  runtimeMismatch,
  planned,
  executed,
  nextCommand: 'npm run owner:runtime-proof:execute',
  generatedAt: now(),
};
writeJson('reports/PASS2151_OWNER_RUNTIME_PROOF_RUNNER.json', report);
console.log(JSON.stringify({ status: report.status, runtimeMismatch, gates: gates.length, execute }, null, 2));
if (execute && strict && report.status !== 'ALL_GATES_EXECUTED_PASS') process.exit(1);
