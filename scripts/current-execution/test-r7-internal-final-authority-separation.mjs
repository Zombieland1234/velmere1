import fs from "node:fs";
import path from "node:path";
import assert from "node:assert/strict";
import crypto from "node:crypto";

const root = process.cwd();
const read = (file) => fs.readFileSync(path.join(root, file), "utf8");
const sha256 = (file) => crypto.createHash("sha256").update(fs.readFileSync(path.join(root, file))).digest("hex");
const contract = JSON.parse(read("config/r7/r7-internal-customer-final-authority.json"));
const progress = JSON.parse(read("config/r7/r7-20-row-progress.json"));
const receipt = JSON.parse(read("config/r7/r7-authority-reconciliation-receipt.json"));

assert.equal(contract.appliesToCandidate, "R7_MERGED_CURRENT_SOURCE");
assert.equal(contract.ancestry.commonBase, "R4");
assert.deepEqual(contract.ancestry.siblingBranches, ["R5", "R6"]);
assert.equal(contract.resolution.realExternalCustomerProofIsInternalFinalGate, false);
assert.equal(contract.resolution.externalPilotIsInternalFinalGate, false);
assert.equal(contract.internalCustomerFinal.externalHumanOrCustomerProofRequired, false);
assert.equal(contract.internalCustomerFinal.externalPilotRequired, false);
assert.equal(progress.denominator, 20);
assert.equal(progress.customerFinalNumerator, 0);
assert.equal(progress.paidValueFinalNumerator, 0);
assert.equal(progress.rows.length, 20);
assert.ok(progress.rows.every((row) => row.customerFinal === false));
assert.ok(progress.rows.every((row) => row.r7AuthorityGate === "OWNER_AUTHORIZED_CURRENT_BYTE_END_TO_END_EXECUTION"));
assert.ok(progress.rows.every((row) => row.r7ExternalPilotInternalFinalGate === false));
assert.ok(progress.rows.every((row) => !row.remainingBlockers.some((value) => /REAL_EXTERNAL_CUSTOMER|EXTERNAL_CUSTOMER_EXECUTION/u.test(value))));
assert.ok(progress.rows.some((row) => row.historicalSourceMapExternalBlockers.includes("REAL_EXTERNAL_CUSTOMER_PROOF")));
assert.equal(receipt.status, "PASS_BOUNDED");
assert.equal(receipt.checks.noActiveExternalCustomerBlocker, true);
assert.equal(receipt.checks.historicalExternalProofPreserved, true);
assert.deepEqual(receipt.sourceBindings, contract.sourceBindings, "receipt sourceBindings must match current authority contract");
for (const [key, file] of [["v4Sha256", contract.sourceBindings.v4Path],["v17Sha256", contract.sourceBindings.v17Path],["r5ProgressSha256", contract.sourceBindings.r5ProgressPath],["r6ProgressSha256", contract.sourceBindings.r6ProgressPath],["r7ProgressSha256", contract.sourceBindings.r7ProgressPath]]) assert.equal(contract.sourceBindings[key], sha256(file), `${key} mismatch`);
const authorityText = read("VELMERE_R7_INTERNAL_CUSTOMER_FINAL_AUTHORITY_RECONCILIATION_2026-08-24.txt");
assert.match(authorityText, /NOT an internal-final prerequisite/u);
assert.match(authorityText, /NON-WEAKENING GUARANTEE/u);
const sourceAuthorityHistory = read("supabase/migrations/20260825000012_r7_source_authority_append_only_history.sql");
assert.match(sourceAuthorityHistory, /r7_source_authority_history/u);
assert.match(sourceAuthorityHistory, /before update or delete/u);
assert.match(sourceAuthorityHistory, /before truncate/u);
assert.match(sourceAuthorityHistory, /on conflict \(github_sha, exact_windows_run_id, exact_windows_run_attempt\)\s+do nothing/u);
assert.match(sourceAuthorityHistory, /insert into velmere_private\.r7_source_authority_history/u);
assert.match(sourceAuthorityHistory, /revoke all on table velmere_private\.r7_source_authority_history\s+from public, anon, authenticated, service_role/u);
process.stdout.write(`${JSON.stringify({schemaVersion:"velmere.r7.internal-final-authority-separation-test.v2",status:"PASS",assertions:31,internalFinalExternalCustomerGate:false,externalPilotGate:"POST_20_OF_20",replacementGate:contract.resolution.activeReplacementGate,allTwentyRowsCorrected:true,historicalMapsPreserved:true,sourceAuthorityHistoryAppendOnly:true,customerFinalCredit:false},null,2)}\n`);
