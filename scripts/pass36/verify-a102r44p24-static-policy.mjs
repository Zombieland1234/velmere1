#!/usr/bin/env node
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
const ROOT=path.resolve(path.dirname(fileURLToPath(import.meta.url)),"../..");
const policy=JSON.parse(fs.readFileSync(path.join(ROOT,"config/pass36/a102r44p24-release-integrity-policy.json"),"utf8"));
const state=JSON.parse(fs.readFileSync(path.join(ROOT,"config/pass36/a102r44p24-action-required-current-state.json"),"utf8"));
const runner=fs.readFileSync(path.join(ROOT,"scripts/pass13/run-partitioned-typescript.mjs"),"utf8");
const helper=fs.readFileSync(path.join(ROOT,"lib/build/complete-json-stdout.mjs"),"utf8");
const lock=fs.readFileSync(path.join(ROOT,"lib/build/release-transaction-lock.mjs"),"utf8");
const checks=[]; const add=(id,ok,detail=null)=>checks.push({id,ok:Boolean(ok),detail});
add("revision",policy.revisionId==="VELMERE_PASS36_A102R44P24_ACTION_REQUIRED_TYPESCRIPT_WORKER_OUTPUT_SINGLE_WRITER_NEXT_ENV_AND_EXACT_LINUX_RELEASE_CLOSURE_NO_LIVE_CREDIT"&&state.revisionId===policy.revisionId);
add("parent",policy.parentRevisionId==="VELMERE_PASS36_A102R44P23_ACTION_REQUIRED_LOCAL_DISPOSABLE_CUSTOMER_LIFECYCLE_REFUND_REVOCATION_DELETE_AND_DURABLE_DELIVERY_NO_LIVE_CREDIT"&&state.parentRevisionId===policy.parentRevisionId);
add("global-no-go",state.globalDecision==="NO_GO");
add("flags-false",[state.LIVE,state.saleEnabled,state.productionApproved,state.worldClassProven].every(v=>v===false));
add("basic-free",policy.nonNegotiable.basicAlwaysFree===true);
add("pro-no-public-checkout",policy.nonNegotiable.proPublicCheckoutAllowed===false);
add("advanced-stop-sale",policy.nonNegotiable.advancedForSale===false);
add("complete-json-helper",helper.includes("process.stdout.write")&&helper.includes("await new Promise"));
add("worker-awaits-flush",runner.includes("await writeJsonToStdoutFully"));
add("legacy-immediate-write-removed",!runner.includes("process.stdout.write(JSON.stringify({idx"));
add("next-env-before",runner.includes("nextEnvBefore"));
add("next-env-after",runner.includes("nextEnvAfter"));
add("next-env-immutable",runner.includes("nextEnvImmutable"));
add("single-writer-o-excl",lock.includes('fs.openSync(c.filePath, "wx"'));
add("single-writer-token",lock.includes("OWNER_OR_TOKEN_MISMATCH"));
add("single-writer-private-mode",lock.includes("0o700")&&lock.includes("0o600"));
add("tests-present",fs.existsSync(path.join(ROOT,"scripts/pass36/test-a102r44p24-typescript-worker-output-boundary.mjs"))&&fs.existsSync(path.join(ROOT,"scripts/pass36/test-a102r44p24-single-writer-next-env-boundary.mjs")));
add("historical-test-migration",fs.existsSync(path.join(ROOT,"config/pass36/a102r44p24-historical-test-lint-migration.json"))&&fs.existsSync(path.join(ROOT,"scripts/pass36/verify-a102r44p24-historical-test-lint-migration.mjs")));
add("source-credits-false",Object.values(state.currentByteCredit).every(v=>v===false));
add("no-live-credit",policy.creditBoundary.liveCredit===false&&policy.creditBoundary.paidSaleCredit===false);
add("active-pass",fs.readFileSync(path.join(ROOT,"VELMERE_ACTIVE_PASS.txt"),"utf8").trim()===policy.revisionId);
const failed=checks.filter(x=>!x.ok); const result={schemaVersion:"velmere.pass36.a102r44p24.static-policy.v1",status:failed.length?"FAIL":"PASS_R44P24_STATIC_POLICY",checks:checks.length,passed:checks.length-failed.length,failed:failed.length,rows:checks};
console.log(JSON.stringify(result,null,2)); if(failed.length)process.exit(1);
