#!/usr/bin/env node
import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";
import { fileURLToPath } from "node:url";
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const approvedRel = "config/pass36/a102r44p16-approved-current-source-changes.json";
const manifestRel = "_velmere/PASS36_A102R44P16_SOURCE_ONLY_MANIFEST.json";
const approved = JSON.parse(fs.readFileSync(path.join(ROOT, approvedRel), "utf8"));
const manifest = JSON.parse(fs.readFileSync(path.join(ROOT, manifestRel), "utf8"));
const parent = JSON.parse(fs.readFileSync(path.join(ROOT, approved.parentManifestPath), "utf8"));
const sha = (bytes) => crypto.createHash("sha256").update(bytes).digest("hex");
const parentManifestBytes = fs.readFileSync(path.join(ROOT, approved.parentManifestPath));
const parentMap = new Map(parent.entries.map((row) => [row.path, row]));
parentMap.set(approved.parentManifestPath, approved.parentManifestEntry);
const currentRows = manifest.entries.filter((row) => row.path !== approvedRel);
const currentMap = new Map(currentRows.map((row) => [row.path, row]));
const added = currentRows.filter((row) => !parentMap.has(row.path));
const deleted = [...parentMap.values()].filter((row) => !currentMap.has(row.path));
const modified = currentRows.filter((row) => { const old = parentMap.get(row.path); return old && (old.byteLength !== row.byteLength || old.sha256 !== row.sha256 || old.mode !== row.mode); }).map((row) => ({ path: row.path, parent: parentMap.get(row.path), current: row }));
const canonical = (value) => Array.isArray(value) ? value.map(canonical) : value && typeof value === "object" ? Object.fromEntries(Object.keys(value).sort().map((key) => [key, canonical(value[key])])) : value;
const stable = (value) => JSON.stringify(canonical(value));
const checks=[]; const check=(id,ok,detail=null)=>checks.push({id,ok:Boolean(ok),detail});
check("schema",approved.schemaVersion==="velmere.pass36.a102r44p16.approved-current-source-changes.v1");
check("revision",approved.revisionId===manifest.revisionId);
check("parent",approved.parentRevisionId===manifest.parentRevisionId&&parent.revisionId===approved.parentRevisionId);
check("parent-manifest-sha",sha(parentManifestBytes)===approved.parentManifestSha256);
check("parent-manifest-entry",approved.parentManifestEntry.path===approved.parentManifestPath&&approved.parentManifestEntry.sha256===approved.parentManifestSha256&&approved.parentManifestEntry.byteLength===parentManifestBytes.length);
check("self-excluded",approved.selfExcludedPath===approvedRel&&approved.sourceManifestExcludedPath===manifestRel);
check("added-count",approved.addedCount===added.length,{expected:approved.addedCount,actual:added.length});
check("modified-count",approved.modifiedCount===modified.length,{expected:approved.modifiedCount,actual:modified.length});
check("deleted-count",approved.deletedCount===deleted.length,{expected:approved.deletedCount,actual:deleted.length});
check("added-exact",stable(approved.added)===stable(added));
check("modified-exact",stable(approved.modified)===stable(modified));
check("deleted-exact",stable(approved.deleted)===stable(deleted));
check("no-test-removal",approved.removedTests===0&&deleted.every((row)=>!row.path.toLowerCase().includes("test")));
check("no-denominator-collapse",approved.denominatorCollapse===false);
check("manifest-binds-ledger",manifest.approvedChangesSha256===sha(fs.readFileSync(path.join(ROOT,approvedRel))));
const failed=checks.filter((row)=>!row.ok); const result={schemaVersion:"velmere.pass36.a102r44p16.approved-source-changes-receipt.v1",status:failed.length?"FAIL":"PASS_R44P16_APPROVED_SOURCE_CHANGES",checks:checks.length,passed:checks.length-failed.length,failed:failed.length,added:added.length,modified:modified.length,deleted:deleted.length,rows:checks};
console.log(JSON.stringify(result,null,2)); if(failed.length)process.exit(1);
