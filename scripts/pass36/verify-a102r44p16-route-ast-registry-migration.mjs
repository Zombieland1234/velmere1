#!/usr/bin/env node
import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";
import { fileURLToPath } from "node:url";
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const load = (rel) => JSON.parse(fs.readFileSync(path.join(ROOT, rel), "utf8"));
const sha = (bytes) => crypto.createHash("sha256").update(bytes).digest("hex");
const migration = load("config/pass36/a102r44p16-route-ast-registry-migration.json");
const registryPath = "config/pass15/route-export-ast-registry.json";
const registry = load(registryPath);
const checks = [];
const check = (id, passed, detail = null) => checks.push({ id, passed: Boolean(passed), detail });
check("schema", migration.schemaVersion === "velmere.pass36.a102r44p16.route-ast-registry-migration.v1");
check("revision", migration.revisionId === "VELMERE_PASS36_A102R44P16_ACTION_REQUIRED_SINGLE_SKU_TRUTH_ANALYSIS_QUEUE_AND_CUSTOMER_CLAIM_CLOSURE_NO_LIVE_CREDIT");
check("denominator-retained", migration.oldDenominator === 254 && migration.newDenominator === 254 && registry.fileCount === 254);
check("methods-retained", migration.oldMethodExportCount === 317 && migration.newMethodExportCount === 317 && registry.methodExportCount === 317);
check("one-row-changed", migration.changedRowCount === 1 && migration.changes?.length === 1);
const row = migration.changes?.[0];
check("checkout-row-only", row?.path === "app/api/checkout/vlm-service/route.ts");
check("method-export-preserved", JSON.stringify(row?.before?.methods) === '["POST"]' && JSON.stringify(row?.after?.methods) === '["POST"]');
check("source-hash-changed", /^[0-9a-f]{64}$/u.test(row?.before?.sha256 ?? "") && /^[0-9a-f]{64}$/u.test(row?.after?.sha256 ?? "") && row.before.sha256 !== row.after.sha256);
check("no-added-or-removed", migration.addedRows?.length === 0 && migration.removedRows?.length === 0);
check("current-registry-hash", sha(fs.readFileSync(path.join(ROOT, registryPath))) === migration.currentRegistrySha256);
const currentRow = registry.rows.find((entry) => entry.path === row?.path);
check("current-row-bound", currentRow?.sha256 === row?.after?.sha256 && currentRow?.byteLength === row?.after?.byteLength && JSON.stringify(currentRow?.methods) === JSON.stringify(row?.after?.methods));
check("diagnostic-only", migration.exactAstReparseCredit === false && registry.exactAstReparseCredit === false && registry.parser?.source === "DIAGNOSTIC_EXTERNAL_ONLY");
check("no-build-live-credit", migration.truthBoundary?.exactRouteAstCredit === false && migration.truthBoundary?.buildBrowserCredit === false && migration.truthBoundary?.saleCredit === false && migration.truthBoundary?.liveCredit === false);
const failed = checks.filter((entry) => !entry.passed);
const result = { schemaVersion: "velmere.pass36.a102r44p16.route-ast-registry-migration-receipt.v1", status: failed.length ? "FAIL" : "PASS_R44P16_ROUTE_AST_REGISTRY_MIGRATION", summary: { checks: checks.length, passed: checks.length - failed.length, failed: failed.length }, checks, truthBoundary: migration.truthBoundary };
console.log(JSON.stringify(result, null, 2));
if (failed.length) process.exit(1);
