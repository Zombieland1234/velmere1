def format_value(value: Any, locale: str) -> str:
    if isinstance(value, bool):
        return {"pl": "tak" if value else "nie", "en": "yes" if value else "no", "de": "ja" if value else "nein"}[locale]
    if value is None:
        return {"pl": "brak", "en": "none", "de": "keine"}[locale]
    if isinstance(value, list):
        return ", ".join(format_value(item, locale) for item in value) or {"pl": "brak", "en": "none", "de": "keine"}[locale]
    if isinstance(value, dict):
        return "; ".join(f"{humanize_token(key, locale)}={format_value(item, locale)}" for key, item in sorted(value.items()))
    return humanize_token(value, locale)

