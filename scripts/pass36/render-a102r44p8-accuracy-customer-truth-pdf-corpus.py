def humanize_token(value: Any, locale: str) -> str:
    text = clean_text(value)
    if text in TOKEN_COPY[locale]:
        return TOKEN_COPY[locale][text]
    if text in TECHNICAL_TERM_COPY:
        return TECHNICAL_TERM_COPY[text][locale]
    return text.replace("_", " ")


